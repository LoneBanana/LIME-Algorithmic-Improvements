"""Generate the Markdown tables quoted in README.md from the result JSON files.

    python3 -m experiments.readme_tables    # writes results/summary.md

Every number in the README's results section comes from this script, so the
README can be re-synchronised after re-running the experiments.
"""

from __future__ import annotations

import json

from .common import MODELS, RESULTS

ORDER = ["1d_logistic", "1d_sine", "1d_bumps", "1d_staircase", "1d_ripple", "moons_mlp", "synth_oracle",
         "synth_mlp", "synth_rf", "friedman_oracle", "friedman_mlp"]
NAMES = {
    "1d_logistic": "1-D logistic", "1d_sine": "1-D sine", "1d_bumps": "1-D bumps", "1d_staircase": "1-D staircase",
    "1d_ripple": "1-D trend + ripple", "moons_mlp": "Two moons · MLP", "synth_oracle": "Synthetic 8-D · true p(y\\|x)",
    "synth_mlp": "Synthetic 8-D · MLP", "synth_rf": "Synthetic 8-D · random forest",
    "friedman_oracle": "Friedman #1 · true function", "friedman_mlp": "Friedman #1 · MLP",
}
METRICS = [("r0.5", "0.5σ"), ("r1", "1σ"), ("r2", "2σ"), ("r4", "4σ"), ("neighborhood_wmse", "LIME nbhd"),
           ("global_mse", "test set")]


def ratio_cell(c: dict) -> str:
    """Bold ▼ / ▲ only if p < 0.05, the means differ by >= 5% and the rank test points the same way."""
    r, p, z = c["mean_ratio"], c["wilcoxon_p"], c["wilcoxon_z"]
    if r is None:
        return "–"
    txt = f"{r:.2f}×" if r >= 0.1 else f"{r:.2g}×"
    if p < 0.05 and abs(r - 1) >= 0.05 and (z < 0) == (r < 1):
        return f"**{txt}** ▼" if r < 1 else f"{txt} ▲"
    return txt


def comparison_table(bench: dict, a: str, b: str) -> list[str]:
    lines = ["| Setting | " + " | ".join(m[1] for m in METRICS) + " |", "|---" * (len(METRICS) + 1) + "|"]
    for k in ORDER:
        comp = bench[k]["comparisons"][f"{a} vs {b}"]
        lines.append(f"| {NAMES[k]} | " + " | ".join(ratio_cell(comp[m]) for m, _ in METRICS) + " |")
    return lines


def main() -> None:
    bench = json.loads((RESULTS / "benchmarks.json").read_text())
    abl = json.loads((RESULTS / "ablations.json").read_text())
    stab = json.loads((RESULTS / "stability.json").read_text())
    quality = json.loads((MODELS / "quality.json").read_text())
    s = bench["settings"]
    out = ["# Summary tables (generated by `python3 -m experiments.readme_tables`)", ""]
    out.append("Cells: ratio of mean MSE (A / B) over the explained instances. **Bold ▼** = A significantly better "
               "(Wilcoxon signed-rank p < 0.05, ≥ 5% difference, and the rank test agrees on the direction); "
               "▲ = A significantly worse by the same rule; plain = no meaningful difference.")

    out += ["", "## ArcTanh-LIME vs LIME with the same query budget", ""]
    out += comparison_table(s, "ArcTanh-LIME", "LIME (matched budget)")
    out += ["", "## ArcTanh-LIME vs LIME fitted on exactly the same points (LIME sample + walk path)", ""]
    out += comparison_table(s, "ArcTanh-LIME", "LIME (same data)")
    out += ["", "## ArcTanh-LIME-δ vs LIME", ""]
    out += comparison_table(s, "ArcTanh-LIME-δ", "LIME")
    out += ["", "## ArcTanh-LIME-δ vs LIME-δ (same anchors, linear members)", ""]
    out += comparison_table(s, "ArcTanh-LIME-δ", "LIME-δ")
    out += ["", "## LIME-δ vs LIME (effect of the anchors alone)", ""]
    out += comparison_table(s, "LIME-δ", "LIME")

    out += ["", "## Mean MSE at 1σ and query cost", "",
            "| Setting | LIME | ArcTanh-LIME | LIME-δ | ArcTanh-LIME-δ | queries LIME / ArcTanh / LIME-δ / ArcTanh-δ (median) |",
            "|---|---|---|---|---|---|"]
    for k in ORDER:
        m = s[k]["methods"]
        mse = " | ".join(f"{m[x]['r1']['mean']:.4g}" for x in ("LIME", "ArcTanh-LIME", "LIME-δ", "ArcTanh-LIME-δ"))
        q = " / ".join(f"{m[x]['queries']['median']:,.0f}" for x in ("LIME", "ArcTanh-LIME", "LIME-δ", "ArcTanh-LIME-δ"))
        out.append(f"| {NAMES[k]} | {mse} | {q} |")

    out += ["", "## ε-walk diagnostics (ArcTanh-LIME)", "",
            "| Setting | median steps up / down | stop reasons (both walks) | fallbacks | mean share of targets outside (lo, hi) |",
            "|---|---|---|---|---|"]
    for k in ORDER:
        w = s[k]["walk"]
        reasons = ", ".join(f"{r} {n}" for r, n in sorted(w["stop_reasons"].items(), key=lambda t: -t[1]))
        fb = ", ".join(f"{r} {n}" for r, n in w["fallbacks"].items())
        out.append(f"| {NAMES[k]} | {w['up_steps']['median']:g} / {w['down_steps']['median']:g} | {reasons} | {fb} | "
                   f"{w['clipped_fraction']['mean']:.3f} |")

    out += ["", "## Attribution vs true gradient (mean cosine; smooth black boxes, d ≥ 2)", "",
            "| Setting | LIME | ArcTanh-LIME |", "|---|---|---|"]
    for k in ORDER:
        if k.startswith("1d_") or k == "synth_rf":
            continue
        m = s[k]["methods"]
        out.append(f"| {NAMES[k]} | {m['LIME']['grad_cosine']['mean']:.3f} | {m['ArcTanh-LIME']['grad_cosine']['mean']:.3f} |")

    out += ["", f"## Seed stability ({stab['n_instances']} instances × {stab['n_seeds']} seeds)", "",
            "| Setting | pairwise cosine LIME | ArcTanh-LIME | relative spread LIME | ArcTanh-LIME | prediction SD LIME | ArcTanh-LIME |",
            "|---|---|---|---|---|---|---|"]
    for k, r in stab["settings"].items():
        L, A = r["methods"]["LIME"], r["methods"]["ArcTanh-LIME"]
        out.append(f"| {NAMES.get(k, k)} | {L['pairwise_cosine']['mean']:.3f} | {A['pairwise_cosine']['mean']:.3f} | "
                   f"{L['relative_spread']['mean']:.3f} | {A['relative_spread']['mean']:.3f} | "
                   f"{L['prediction_sd']['mean']:.4f} | {A['prediction_sd']['mean']:.4f} |")

    ref = "ArcTanh-LIME (default)"
    show = ["LIME", "LIME, intercept pinned to f(x0)", "fit = link space only (pure tanh⁻¹ regression)",
            "asymptotes = global output range (no walk)", "asymptotes fixed to [0, 1] (no walk)",
            "asymptotes = walk ∪ sample range", "walk not confined to the data box", "pin origin: g(x0) = f(x0)",
            "walk points not used in fit",
            "ε = 0.05 (80 steps)", "ε = 0.4 (10 steps)", "tol_rel = 0 (strict improvement)", "margin = 0",
            "margin = 0.2"]
    for metric, label in (("r0.5", "0.5σ"), ("r1", "1σ"), ("r2", "2σ")):
        settings = list(abl["single"].keys())
        out += ["", f"## Single-anchor ablations at {label} (ratio to the default ArcTanh-LIME)", "",
                "| Variant | " + " | ".join(NAMES[k] for k in settings) + " |", "|---" * (len(settings) + 1) + "|"]
        for v in show:
            cells = []
            for k in settings:
                comp = abl["single"][k]["comparisons"].get(f"{v} vs {ref}")
                cells.append(ratio_cell(comp[metric]) if comp else "n/a")
            out.append(f"| {v} | " + " | ".join(cells) + " |")

    ref_e = "ArcTanh-LIME-δ (δ = 1, default)"
    settings = list(abl["ensemble"].keys())
    for metric, label in (("r1", "1σ"), ("r4", "4σ"), ("global_mse", "test set")):
        out += ["", f"## Ensemble ablations at {label} (ratio to ArcTanh-LIME-δ with δ = 1)", "",
                "| Variant | median queries (" + NAMES[settings[-1]] + ") | " + " | ".join(NAMES[k] for k in settings) + " |",
                "|---" * (len(settings) + 2) + "|"]
        for v in abl["ensemble"][settings[0]]["methods"]:
            if v == ref_e:
                continue
            cells = []
            for k in settings:
                comp = abl["ensemble"][k]["comparisons"].get(f"{v} vs {ref_e}")
                cells.append(ratio_cell(comp[metric]) if comp else "n/a")
            q = abl["ensemble"][settings[-1]]["methods"][v]["queries"]["median"]
            out.append(f"| {v} | {q:,.0f} | " + " | ".join(cells) + " |")

    out += ["", "## Black-box quality (held-out)", "", "| Model | metric |", "|---|---|"]
    for k, v in quality.items():
        metric = ", ".join(f"{a} = {b:.3f}" for a, b in v.items() if a != "train_seconds")
        out.append(f"| {k} | {metric} |")
    (RESULTS / "summary.md").write_text("\n".join(out) + "\n")
    print("wrote results/summary.md")


if __name__ == "__main__":
    main()
