"""Ablations of ArcTanh-LIME's design choices and of the +/- delta ensemble.

    python3 -m experiments.run_ablations
"""

from __future__ import annotations

import json
import time

from .aggregate import comparison_table, method_table, summarize
from .common import RESULTS, get_setting, prepare_models, run_parallel

SINGLE_SETTINGS = ["1d_sine", "1d_bumps", "1d_ripple", "moons_mlp", "synth_mlp", "synth_rf", "friedman_oracle",
                   "friedman_mlp"]
ENSEMBLE_SETTINGS = ["1d_sine", "moons_mlp", "synth_mlp", "friedman_mlp"]
TABLE_RADII = [0.5, 1.0, 2.0, 4.0]


def single_variants(s) -> list[tuple]:
    v = [
        ("LIME", "LIME", None, None),
        ("LIME, intercept pinned to f(x0)", "LIME (pinned intercept)", None, None),
        ("ArcTanh-LIME (default)", "ArcTanh-LIME", None, None),
        ("asymptotes = walk ∪ sample range", "ArcTanh-LIME", {"asymptotes": "walk+samples"}, None),
        ("walk not confined to the data box", "ArcTanh-LIME (unbounded walk)", None, None),
        ("asymptotes = global output range (no walk)", "ArcTanh-LIME",
         {"asymptotes": "fixed", "fixed_bounds": s.output_range()}, None),
    ]
    if s.output == "probability":
        v.append(("asymptotes fixed to [0, 1] (no walk)", "ArcTanh-LIME",
                  {"asymptotes": "fixed", "fixed_bounds": (0.0, 1.0)}, None))
    v += [
        ("fit = link space only (pure tanh⁻¹ regression)", "ArcTanh-LIME", {"fit": "link"}, None),
        ("pin origin: g(x0) = f(x0)", "ArcTanh-LIME", {"pin_origin": True}, None),
        ("walk points not used in fit", "ArcTanh-LIME", {"use_walk_points": False}, None),
        ("ε = 0.05 (80 steps)", "ArcTanh-LIME", {"epsilon": 0.05, "max_steps": 80}, None),
        ("ε = 0.2 (20 steps)", "ArcTanh-LIME", {"epsilon": 0.2, "max_steps": 20}, None),
        ("ε = 0.4 (10 steps)", "ArcTanh-LIME", {"epsilon": 0.4, "max_steps": 10}, None),
        ("walk budget 10 steps (≤ 1 std)", "ArcTanh-LIME", {"max_steps": 10}, None),
        ("tol_rel = 0 (strict improvement)", "ArcTanh-LIME", {"tol_rel": 0.0}, None),
        ("tol_rel = 0.01", "ArcTanh-LIME", {"tol_rel": 0.01}, None),
        ("margin = 0", "ArcTanh-LIME", {"margin": 0.0}, None),
        ("margin = 0.2", "ArcTanh-LIME", {"margin": 0.2}, None),
    ]
    return v


ENSEMBLE_VARIANTS = [
    ("LIME", "LIME", None, None),
    ("ArcTanh-LIME", "ArcTanh-LIME", None, None),
    ("ArcTanh-LIME-δ (δ = 1, default)", "ArcTanh-LIME-δ", None, None),
    ("δ = 0.5", "ArcTanh-LIME-δ", None, {"delta": 0.5}),
    ("δ = 2", "ArcTanh-LIME-δ", None, {"delta": 2.0}),
    ("rings = 2 (anchors at ±δ, ±2δ)", "ArcTanh-LIME-δ", None, {"rings": 2}),
    ("bandwidth = δ (softer blend)", "ArcTanh-LIME-δ", None, {"bandwidth": 1.0}),
    ("bandwidth = δ/4 (sharper blend)", "ArcTanh-LIME-δ", None, {"bandwidth": 0.25}),
    ("LIME-δ (δ = 1)", "LIME-δ", None, None),
    ("LIME-δ, rings = 2", "LIME-δ", None, {"rings": 2}),
]


def tasks_for(setting: str, variants: list[tuple]) -> list[dict]:
    s = get_setting(setting)
    return [{"setting": setting, "index": i, "seed": i + 1, "methods": variants} for i in range(len(s.instances))]


def run_group(settings: list[str], variants_fn, reference: str) -> dict:
    out = {}
    for name in settings:
        t0 = time.time()
        variants = variants_fn(get_setting(name))
        records = run_parallel(tasks_for(name, variants))
        labels = [v[0] for v in variants]
        comps = [(lab, reference) for lab in labels if lab != reference]
        # every variant also against plain LIME, and pinned ArcTanh-LIME against pinned LIME (like for like)
        comps += [(lab, "LIME") for lab in labels if lab not in (reference, "LIME")]
        pinned = ("pin origin: g(x0) = f(x0)", "LIME, intercept pinned to f(x0)")
        if all(p in labels for p in pinned):
            comps.append(pinned)
        summary = summarize(records, comps)
        summary["title"] = get_setting(name).title
        out[name] = summary
        print(f"{name}: {len(records)} instances, {len(variants)} variants in {time.time() - t0:.1f}s")
    return out


def main() -> None:
    prepare_models(verbose=False)
    single = run_group(SINGLE_SETTINGS, single_variants, "ArcTanh-LIME (default)")
    ensemble = run_group(ENSEMBLE_SETTINGS, lambda _: ENSEMBLE_VARIANTS, "ArcTanh-LIME-δ (δ = 1, default)")
    (RESULTS / "ablations.json").write_text(json.dumps({"single": single, "ensemble": ensemble}, indent=1))
    md = ["# Ablations (generated by `python3 -m experiments.run_ablations`)", "",
          "Comparison cells: `mean-MSE ratio variant/reference · share of instances where the variant wins · "
          "Wilcoxon p`. Ratios < 1 mean the variant is better than the reference (the default)."]
    for group, data in (("Single-anchor ArcTanh-LIME", single), ("±δ ensemble", ensemble)):
        md += ["", f"## {group}"]
        for name, s in data.items():
            md += ["", f"### {s['title']} (`{name}`, {s['n_instances']} instances)", ""]
            md.append(method_table(s, TABLE_RADII))
            md.append("")
            md.append(comparison_table(s, TABLE_RADII))
    (RESULTS / "ablations.md").write_text("\n".join(md) + "\n")
    print("wrote results/ablations.json and results/ablations.md")


if __name__ == "__main__":
    main()
