"""LIME vs ArcTanh-LIME on real diabetes-risk data: 4 datasets x 4 black boxes = 16 settings.

    python3 -m experiments.diabetes download   # once (data/raw is git-ignored)
    python3 -m experiments.run_diabetes
"""

from __future__ import annotations

import json
import time

from .aggregate import comparison_table, method_table, summarize
from .common import NUM_SAMPLES, RADII, RESULTS, get_setting, run_parallel
from .diabetes import ATTRIBUTION, MODEL_TITLES, MODELS, SOURCES, TITLES, load, prepare_models, setting_names

OUT = RESULTS / "diabetes"

METHODS = [
    ("LIME", "LIME", None, None),
    ("ArcTanh-LIME", "ArcTanh-LIME", None, None),
    ("LIME (same data)", "LIME (same data)", None, None),
    ("LIME (matched budget)", "LIME (matched budget)", None, None),
    ("ArcTanh-LIME, [0,1] asymptotes (no walk)", "ArcTanh-LIME", {"asymptotes": "fixed", "fixed_bounds": (0.0, 1.0)},
     None),
    ("ArcTanh-LIME, unbounded walk", "ArcTanh-LIME (unbounded walk)", None, None),
    ("LIME-δ", "LIME-δ", None, None),
    ("ArcTanh-LIME-δ", "ArcTanh-LIME-δ", None, None),
]

COMPARISONS = [
    ("ArcTanh-LIME", "LIME (matched budget)"),
    ("ArcTanh-LIME", "LIME (same data)"),
    ("ArcTanh-LIME, [0,1] asymptotes (no walk)", "LIME"),
    ("ArcTanh-LIME, [0,1] asymptotes (no walk)", "ArcTanh-LIME"),
    ("ArcTanh-LIME, unbounded walk", "ArcTanh-LIME"),
    ("LIME-δ", "LIME"),
    ("ArcTanh-LIME-δ", "LIME-δ"),
    ("ArcTanh-LIME-δ", "LIME"),
]
TABLE_RADII = [0.5, 1.0, 2.0, 4.0]


def main() -> None:
    print("black boxes:")
    quality = prepare_models()
    OUT.mkdir(parents=True, exist_ok=True)
    raw_dir = OUT / "raw"
    raw_dir.mkdir(exist_ok=True)
    summaries = {}
    for name in setting_names():
        t0 = time.time()
        s = get_setting(name)
        tasks = [{"setting": name, "index": i, "seed": i + 1, "methods": METHODS} for i in range(len(s.instances))]
        records = run_parallel(tasks)
        (raw_dir / f"{name}.json").write_text(json.dumps(records))
        summary = summarize(records, COMPARISONS)
        _, key, mname = name.split("_")
        summary.update({"title": s.title, "dataset": key, "model": mname, "d": s.d,
                        "quality": quality[f"{key}_{mname}"]})
        summaries[name] = summary
        print(f"{name}: {len(records)} instances in {time.time() - t0:.1f}s")
    datasets = {}
    for key in SOURCES:
        d = load(key)
        datasets[key] = {"title": TITLES[key], "features": d.names, "n_train": len(d.X_train),
                         "n_test": len(d.X_test), "positive_rate": sum(d.y_train + d.y_test) / (len(d.y_train) + len(d.y_test)),
                         "attribution": ATTRIBUTION[key]}
    payload = {"radii": RADII, "num_samples": NUM_SAMPLES, "models": {m: MODEL_TITLES[m] for m in MODELS},
               "datasets": datasets, "settings": summaries}
    (OUT / "benchmarks.json").write_text(json.dumps(payload, indent=1))
    md = ["# Diabetes-risk benchmark (generated by `python3 -m experiments.run_diabetes`)", "",
          "Cells of the comparison tables: `mean-MSE ratio A/B · share of instances where A beats B · "
          "Wilcoxon signed-rank p`. Ratios < 1 favour A."]
    for name, s in summaries.items():
        md += ["", f"## {s['title']}  (`{name}`, d = {s['d']}, {s['n_instances']} instances)", "",
               f"Black-box quality: `{s['quality']}`", "", method_table(s, TABLE_RADII), "",
               comparison_table(s, TABLE_RADII)]
    (OUT / "benchmarks.md").write_text("\n".join(md) + "\n")
    print(f"wrote {OUT / 'benchmarks.json'} and {OUT / 'benchmarks.md'}")


if __name__ == "__main__":
    main()
