"""Main benchmark: LIME vs ArcTanh-LIME (+ the +/- delta ensembles) on every setting.

    python3 -m experiments.run_benchmarks            # all settings
    python3 -m experiments.run_benchmarks moons_mlp  # a subset
"""

from __future__ import annotations

import json
import sys
import time

from .aggregate import comparison_table, method_table, summarize
from .common import (GLOBAL_POINTS, NEIGHBORHOOD_POINTS, NUM_SAMPLES, ONE_D, RADII, RESULTS, SPHERE_POINTS, TABULAR,
                     get_setting, main_tasks, prepare_models, run_parallel)

COMPARISONS = [
    ("ArcTanh-LIME", "LIME"),
    ("ArcTanh-LIME", "LIME (matched budget)"),
    ("ArcTanh-LIME", "LIME (same data)"),
    ("LIME-δ", "LIME"),
    ("ArcTanh-LIME-δ", "LIME-δ"),
    ("ArcTanh-LIME-δ", "ArcTanh-LIME"),
    ("ArcTanh-LIME-δ", "LIME"),
]
TABLE_RADII = [0.5, 1.0, 2.0, 4.0]


def main(settings: list[str]) -> None:
    print("black boxes:")
    quality = prepare_models()
    raw_dir = RESULTS / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    all_summaries = {}
    summary_path = RESULTS / "benchmarks.json"
    if summary_path.exists():
        all_summaries = json.loads(summary_path.read_text()).get("settings", {})
    for name in settings:
        t0 = time.time()
        records = run_parallel(main_tasks(name))
        (raw_dir / f"{name}.json").write_text(json.dumps(records))
        summary = summarize(records, COMPARISONS)
        summary["title"] = get_setting(name).title
        summary["d"] = get_setting(name).d
        summary["quality"] = quality.get(name)
        all_summaries[name] = summary
        print(f"{name}: {len(records)} instances in {time.time() - t0:.1f}s")
    order = [s for s in ONE_D + TABULAR if s in all_summaries]
    payload = {"radii": RADII, "num_samples": NUM_SAMPLES, "sphere_points": SPHERE_POINTS,
               "neighborhood_points": NEIGHBORHOOD_POINTS, "global_points": GLOBAL_POINTS,
               "settings": {k: all_summaries[k] for k in order}}
    summary_path.write_text(json.dumps(payload, indent=1))
    md = ["# Benchmark results (generated by `python3 -m experiments.run_benchmarks`)", ""]
    md.append("Cells of the comparison tables: `mean-MSE ratio A/B · share of instances where A beats B · "
              "Wilcoxon signed-rank p`. Ratios < 1 favour A.")
    for name in order:
        s = all_summaries[name]
        md += ["", f"## {s['title']}  (`{name}`, d = {s['d']}, {s['n_instances']} instances)", ""]
        if s.get("quality"):
            md.append(f"Black-box quality: `{s['quality']}`")
            md.append("")
        md.append(method_table(s, TABLE_RADII))
        md.append("")
        md.append(comparison_table(s, TABLE_RADII))
        if "walk" in s:
            w = s["walk"]
            md.append("")
            md.append(f"ε-walk: median steps up {w['up_steps']['median']:g}, down {w['down_steps']['median']:g}; "
                      f"stop reasons {w['stop_reasons']}; fallbacks {w['fallbacks']}; "
                      f"mean share of clipped targets {w['clipped_fraction']['mean']:.3f}")
    (RESULTS / "benchmarks.md").write_text("\n".join(md) + "\n")
    print(f"wrote {summary_path} and {RESULTS / 'benchmarks.md'}")


if __name__ == "__main__":
    main(sys.argv[1:] or ONE_D + TABULAR)
