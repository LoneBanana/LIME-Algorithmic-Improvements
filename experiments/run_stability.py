"""Seed stability of the explanations (same instance, different perturbation samples).

    python3 -m experiments.run_stability
"""

from __future__ import annotations

import json
import math
import time

from atlime import Rng
from atlime.metrics import cosine, mean, median, sphere_set

from .common import RESULTS, build, get_setting, prepare_models, run_parallel

SETTINGS = ["1d_bumps", "moons_mlp", "synth_mlp", "synth_rf", "friedman_mlp"]
METHODS = ["LIME", "ArcTanh-LIME"]
N_INSTANCES = 15
N_SEEDS = 5


def stability_task(task: dict) -> dict:
    s = get_setting(task["setting"])
    x0 = s.instances[task["index"]]
    probes = sphere_set(s.f, x0, s.scale, [1.0], 50, Rng(4242 + task["index"]), s.bounds)["points"][0]
    out = {}
    for method in METHODS:
        explainer = build(method, s)
        attrs, preds = [], []
        for seed in range(N_SEEDS):
            res = explainer.explain(s.f, x0, Rng(10_000 * (seed + 1) + task["index"]))
            attrs.append(res.attribution)
            preds.append([res.surrogate.predict(p) for p in probes])
        pair_cos = [cosine(attrs[i], attrs[j]) for i in range(N_SEEDS) for j in range(i + 1, N_SEEDS)]
        center = [mean([a[k] for a in attrs]) for k in range(s.d)]
        cn = math.sqrt(sum(c * c for c in center))
        spread = mean([math.sqrt(sum((a[k] - center[k]) ** 2 for k in range(s.d))) for a in attrs]) / cn if cn else 0
        pred_sd = mean([math.sqrt(mean([(p[i] - mean([q[i] for q in preds])) ** 2 for p in preds]))
                        for i in range(len(probes))])
        out[method] = {"pairwise_cosine": mean(pair_cos), "relative_spread": spread, "prediction_sd": pred_sd}
    return out


def main() -> None:
    prepare_models(verbose=False)
    results = {}
    for name in SETTINGS:
        t0 = time.time()
        recs = run_parallel([{"setting": name, "index": i} for i in range(N_INSTANCES)], fn=stability_task)
        results[name] = {
            "title": get_setting(name).title,
            "methods": {m: {k: {"mean": mean([r[m][k] for r in recs]), "median": median([r[m][k] for r in recs])}
                            for k in ("pairwise_cosine", "relative_spread", "prediction_sd")} for m in METHODS},
        }
        print(f"{name}: {time.time() - t0:.1f}s")
    (RESULTS / "stability.json").write_text(json.dumps({"n_instances": N_INSTANCES, "n_seeds": N_SEEDS,
                                                        "settings": results}, indent=1))
    md = ["# Seed stability (generated by `python3 -m experiments.run_stability`)", "",
          f"{N_INSTANCES} instances × {N_SEEDS} seeds per setting. *Pairwise cosine*: mean cosine similarity "
          "between the attribution vectors of different seeds (1 = identical direction). *Relative spread*: mean "
          "distance of an attribution to the across-seed mean, divided by the norm of that mean. *Prediction SD*: "
          "across-seed standard deviation of the surrogate's prediction at 50 fixed points 1 std away.", "",
          "| Setting | Method | Pairwise cosine | Relative spread | Prediction SD |", "|---|---|---|---|---|"]
    for name, r in results.items():
        for m in METHODS:
            v = r["methods"][m]
            md.append(f"| {r['title']} | {m} | {v['pairwise_cosine']['mean']:.4f} | "
                      f"{v['relative_spread']['mean']:.4f} | {v['prediction_sd']['mean']:.4g} |")
    (RESULTS / "stability.md").write_text("\n".join(md) + "\n")
    print("wrote results/stability.json and results/stability.md")


if __name__ == "__main__":
    main()
